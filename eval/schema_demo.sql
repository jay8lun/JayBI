BEGIN;

DROP TABLE IF EXISTS sales_target;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS emp;
DROP TABLE IF EXISTS dept;

CREATE TABLE dept (
    dept_id   INT PRIMARY KEY,
    dept_name VARCHAR(50) NOT NULL,
    region    VARCHAR(20) NOT NULL
);

CREATE TABLE emp (
    emp_id    INT PRIMARY KEY,
    emp_name  VARCHAR(50) NOT NULL,
    dept_id   INT REFERENCES dept(dept_id),
    salary    NUMERIC(10,2),          -- 列权限敏感列（analyst_ro 禁用）
    city      VARCHAR(30),
    hire_date DATE
);

CREATE TABLE orders (
    order_id   INT PRIMARY KEY,
    emp_id     INT REFERENCES emp(emp_id),
    amount     NUMERIC(12,2),
    cost_price NUMERIC(12,2),        -- 列权限敏感列（analyst_ro 禁用）
    status     VARCHAR(10),          -- completed / pending / cancelled
    order_date DATE,
    region     VARCHAR(20)           -- 行权限过滤列（analyst_ro 仅华东 / viewer_south 仅华南）
);

CREATE TABLE sales_target (
    target_id     INT PRIMARY KEY,
    dept_id       INT REFERENCES dept(dept_id),
    quarter       VARCHAR(10),       -- 如 2025Q1
    target_amount NUMERIC(12,2)
);

